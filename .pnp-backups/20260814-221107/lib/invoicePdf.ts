const encoder = new TextEncoder();

type PdfObject = Uint8Array;
type FontName = "F1" | "F2" | "F3" | "F4";

function encode(value: string): Uint8Array {
  return encoder.encode(value);
}

function concatBytes(...chunks: Uint8Array[]): Uint8Array {
  const length = chunks.reduce((sum, chunk) => sum + chunk.length, 0);
  const output = new Uint8Array(length);
  let offset = 0;

  for (const chunk of chunks) {
    output.set(chunk, offset);
    offset += chunk.length;
  }

  return output;
}

function base64ToBytes(value: string): Uint8Array {
  const binary = atob(value);
  const output = new Uint8Array(binary.length);

  for (let index = 0; index < binary.length; index += 1) {
    output[index] = binary.charCodeAt(index);
  }

  return output;
}

function ascii(value: string): string {
  return value
    .normalize("NFKD")
    .replace(/[^\x20-\x7E]/g, "")
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)");
}

function truncate(value: string, length: number): string {
  const cleaned = ascii(value.trim());
  return cleaned.length > length
    ? `${cleaned.slice(0, Math.max(0, length - 3))}...`
    : cleaned;
}

function text(
  value: string,
  x: number,
  y: number,
  size = 10,
  font: FontName = "F1",
  color = "0.10 0.10 0.10",
): string {
  return `${color} rg BT /${font} ${size} Tf ${x} ${y} Td (${ascii(
    value,
  )}) Tj ET\n`;
}

function rightText(
  value: string,
  rightX: number,
  y: number,
  size = 10,
  font: FontName = "F1",
  color = "0.10 0.10 0.10",
): string {
  const estimatedWidth = ascii(value).length * size * 0.52;
  return text(
    value,
    Math.max(20, rightX - estimatedWidth),
    y,
    size,
    font,
    color,
  );
}

function centeredText(
  value: string,
  centerX: number,
  y: number,
  size = 10,
  font: FontName = "F1",
  color = "0.10 0.10 0.10",
): string {
  const estimatedWidth = ascii(value).length * size * 0.52;
  return text(value, centerX - estimatedWidth / 2, y, size, font, color);
}

function fillRect(
  x: number,
  y: number,
  width: number,
  height: number,
  color: string,
): string {
  return `${color} rg ${x} ${y} ${width} ${height} re f\n`;
}

function strokeRect(
  x: number,
  y: number,
  width: number,
  height: number,
  color: string,
  lineWidth = 1,
): string {
  return `${color} RG ${lineWidth} w ${x} ${y} ${width} ${height} re S\n`;
}

function line(
  x1: number,
  y1: number,
  x2: number,
  y2: number,
  color: string,
  lineWidth = 1,
): string {
  return `${color} RG ${lineWidth} w ${x1} ${y1} m ${x2} ${y2} l S\n`;
}

function drawImage(
  name: "Lips" | "Script",
  x: number,
  y: number,
  width: number,
  height: number,
): string {
  return `q ${width} 0 0 ${height} ${x} ${y} cm /${name} Do Q\n`;
}

function wrapWords(value: string, maxCharacters: number, maxLines: number): string[] {
  const words = ascii(value.replace(/\s+/g, " ").trim()).split(" ");
  const lines: string[] = [];
  let current = "";

  for (const word of words) {
    const next = current ? `${current} ${word}` : word;

    if (next.length <= maxCharacters) {
      current = next;
      continue;
    }

    if (current) {
      lines.push(current);
    }

    current = word;

    if (lines.length >= maxLines) {
      break;
    }
  }

  if (current && lines.length < maxLines) {
    lines.push(current);
  }

  if (words.length > 0 && lines.length === maxLines) {
    const joined = lines.join(" ");
    const original = words.join(" ");
    if (joined.length < original.length) {
      lines[maxLines - 1] = truncate(lines[maxLines - 1], maxCharacters);
    }
  }

  return lines;
}

function imageObject(
  jpeg: Uint8Array,
  width: number,
  height: number,
): PdfObject {
  return concatBytes(
    encode(
      `<< /Type /XObject /Subtype /Image /Width ${width} /Height ${height} ` +
        `/ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode ` +
        `/Length ${jpeg.length} >>\nstream\n`,
    ),
    jpeg,
    encode("\nendstream"),
  );
}

function streamObject(stream: string): PdfObject {
  const bytes = encode(stream);
  return concatBytes(
    encode(`<< /Length ${bytes.length} >>\nstream\n`),
    bytes,
    encode("endstream"),
  );
}

